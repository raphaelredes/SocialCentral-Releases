--   English (enUS/enGB default fallback)
--   Portuguese (ptBR/ptPT)
--   Spanish (esES/esMX)
-- Respects the player's chosen language/textLocale in World of Warcraft Options.
local L = setmetatable({}, {
    __index = function(_, key)
        if type(key) ~= "string" then
            return key
        end
        local mapped = key
            :gsub("%f[%w]Clans%f[%W]", "Guilds")
            :gsub("%f[%w]Clan%f[%W]", "Guild")
            :gsub("%f[%w]CLANS%f[%W]", "GUILDS")
            :gsub("%f[%w]CLAN%f[%W]", "GUILD")
            :gsub("%f[%w]clans%f[%W]", "guilds")
            :gsub("%f[%w]clan%f[%W]", "guild")
        return mapped
    end,
})

